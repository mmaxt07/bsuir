// rectangle.cpp
#include <iostream>
using namespace std;

/**
 * @class Rectangle
 * @brief Класс для работы с геометрическим прямоугольником на координатной плоскости.
 * @details Стороны прямоугольника параллельны осям координат. Состояние определяется
 * двумя диагональными точками: fpos (левая-нижняя) и spos (правая-верхняя).
 */
class Rectangle
{
private:
    struct
    {
        int x, y;
    } fpos, spos;

public:
    /**
     * @brief Конструктор по умолчанию.
     * @details Инициализирует прямоугольник с нулевыми координатами (вырожденный в точку (0,0)).
     */
    Rectangle()
    {
        fpos.y = fpos.x = 0;
        spos.y = spos.x = 0;
    }

    /**
     * @brief Конструктор с явным указанием координат двух точек.
     * @details Автоматически нормализует координаты так, чтобы fpos гарантированно
     * стала левым-нижним углом, а spos — правым-верхним.
     * @param[in] x1 Координата X первой точки.
     * @param[in] y1 Координата Y первой точки.
     * @param[in] x2 Координата X второй точки.
     * @param[in] y2 Координата Y второй точки.
     */
    explicit Rectangle(int x1, int y1, int x2, int y2)
    {
        fpos.x = (x1 < x2) ? x1 : x2;
        spos.x = (x1 > x2) ? x1 : x2;
        fpos.y = (y1 < y2) ? y1 : y2;
        spos.y = (y1 > y2) ? y1 : y2;
    }

    /**
     * @brief Метод получения и вывода координат вершин.
     * @details Выводит в консоль координаты всех четырех вершин прямоугольника.
     */
    void getcoord();

    /**
     * @brief Метод перемещения (сдвига) прямоугольника.
     * @details Сдвигает прямоугольник на плоскости на заданный вектор (rx, ry).
     * @param[in] rx Сдвиг по оси X.
     * @param[in] ry Сдвиг по оси Y.
     */
    void drag(int rx, int ry);

    /**
     * @brief Метод пропорционального сжатия прямоугольника.
     * @details Уменьшает координаты вершин прямоугольника в k раз относительно начала координат.
     * @param[in] k Коэффициент сжатия (должен быть отличен от нуля).
     */
    void scalein(int k);

    /**
     * @brief Метод пропорционального расширения прямоугольника.
     * @details Увеличивает координаты вершин прямоугольника в k раз относительно начала координат.
     * @param[in] k Коэффициент расширения.
     */
    void scaleout(int k);

    /**
     * @brief Оператор префиксного инкремента (++rect).
     * @details Сдвигает прямоугольник по диагонали на единицу вверх и вправо перед использованием.
     * @return Rectangle& Ссылка на текущий измененный объект.
     */
    Rectangle operator++();

    /**
     * @brief Оператор постфиксного инкремента (rect++).
     * @details Сдвигает прямоугольник по диагонали на единицу вверх и вправо после использования.
     * @param[in] Неиспользуемый параметр int для отличия от префиксной формы.
     * @return Rectangle Старая копия объекта до его изменения.
     */
    Rectangle operator++(int);

    /**
     * @brief Оператор префиксного декремента (--rect).
     * @details Сдвигает прямоугольник по диагонали на единицу вниз и влево перед использованием.
     * @return Rectangle& Ссылка на текущий измененный объект.
     */
    Rectangle operator--();

    /**
     * @brief Оператор постфиксного декремента (rect--).
     * @details Сдвигает прямоугольник по диагонали на единицу вниз и влево после использования.
     * @param[in] Неиспользуемый параметр int для отличия от префиксной формы.
     * @return Rectangle Старая копия объекта до его изменения.
     */
    Rectangle operator--(int);

    /**
     * @brief Оператор геометрического сложения двух прямоугольников.
     * @details Вычисляет минимальный общий охватывающий прямоугольник (Bounding Box) для двух фигур.
     * @param[in] rect Второй прямоугольник для сложения.
     * @return Rectangle Новый прямоугольник, вмещающий в себя оба исходных.
     */
    Rectangle operator+(const Rectangle &rect);

    /**
     * @brief Оператор составного присваивания со сложением.
     * @details Расширяет текущий прямоугольник до размеров общего Bounding Box со вторым прямоугольником.
     * @param[in] rect Второй прямоугольник.
     * @return Rectangle& Ссылка на текущий измененный объект.
     */
    Rectangle operator+=(const Rectangle &rect);

    /**
     * @brief Оператор геометрического вычитания (пересечения) двух прямоугольников.
     * @details Находит область их взаимного наложения (Intersection).
     * @param[in] rect Второй прямоугольник.
     * @return Rectangle Новый прямоугольник, представляющий область пересечения.
     */
    Rectangle operator-(const Rectangle &rect);

    /**
     * @brief Оператор составного присваивания с вычитанием.
     * @details Заменяет текущий прямоугольник областью его пересечения со вторым прямоугольником.
     * @param[in] rect Второй прямоугольник.
     * @return Rectangle& Ссылка на текущий измененный объект.
     */
    Rectangle operator-=(const Rectangle &rect);
};
